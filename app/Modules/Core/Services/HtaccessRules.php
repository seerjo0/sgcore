<?php

namespace App\Modules\Core\Services;

/**
 * The package ships its own .htaccess (rewrite + deny rules), but a real
 * installation's .htaccess also holds blocks written by the host: cPanel's
 * MultiPHP handler, redirects, hotlink protection, user rules. Overwriting the
 * file therefore resets the domain's PHP version.
 *
 * From 1.2.2 the packaged rules live between `# BEGIN sgcore` / `# END sgcore`
 * markers, and an update replaces *only* that block. When the installed file
 * predates the markers, it is migrated once: the legacy generated block is
 * dropped, everything else is kept and the cPanel handler is re-appended if the
 * rewrite wiped it.
 */
final class HtaccessRules
{
    public const BEGIN = '# BEGIN sgcore';

    public const END = '# END sgcore';

    private const CPANEL_START = '# php -- BEGIN cPanel-generated handler';

    private const CPANEL_END = '# php -- END cPanel-generated handler';

    /** First line of the rules this project generated before the markers existed. */
    private const LEGACY_HEADERS = [
        '/^#\s*sgcore shared-hosting rules/i',
        '/^#\s*sgcore package rules/i',
        '/^#\s*sgcore public rules/i',
    ];

    /**
     * cPanel wraps its directive in comment markers; other hosts only add a bare
     * AddHandler/AddType line, which is kept verbatim as well.
     */
    public static function handler(string $htaccess): string
    {
        if ($htaccess === '') {
            return '';
        }

        $start = strpos($htaccess, self::CPANEL_START);

        if ($start !== false) {
            $end = strpos($htaccess, self::CPANEL_END, $start);
            $end = $end === false ? strlen($htaccess) : $end + strlen(self::CPANEL_END);

            return trim(substr($htaccess, $start, $end - $start));
        }

        $lines = [];

        foreach (preg_split('/\R/', $htaccess) ?: [] as $line) {
            if (preg_match('/^\s*(?:AddHandler|AddType)\s+\S*php\S*/i', $line) === 1) {
                $lines[] = rtrim($line);
            }
        }

        return trim(implode("\n", $lines));
    }

    /** The managed block (markers included), or null when not marked yet. */
    public static function block(string $htaccess): ?string
    {
        $start = strpos($htaccess, self::BEGIN);

        if ($start === false) {
            return null;
        }

        $end = strpos($htaccess, self::END, $start);

        if ($end === false) {
            return null;
        }

        return trim(substr($htaccess, $start, $end + strlen(self::END) - $start));
    }

    public static function hasBlock(string $htaccess): bool
    {
        return self::block($htaccess) !== null;
    }

    public static function wrap(string $rules): string
    {
        return self::BEGIN."\n".trim($rules)."\n".self::END;
    }

    /**
     * Merge the incoming packaged rules into the file currently on disk,
     * touching only the sgcore block.
     */
    public static function merge(string $existing, string $incoming): string
    {
        $block = self::block($incoming) ?? self::wrap($incoming);

        if (trim($existing) === '') {
            return $block."\n";
        }

        if (self::hasBlock($existing)) {
            $start = (int) strpos($existing, self::BEGIN);
            $end = (int) strpos($existing, self::END, $start) + strlen(self::END);

            $before = rtrim(substr($existing, 0, $start));
            $after = ltrim(substr($existing, $end));

            $out = ($before === '' ? '' : $before."\n\n").$block;

            if ($after !== '') {
                $out .= "\n\n".$after;
            }

            return rtrim($out)."\n";
        }

        // File from an older install (or hand-written): keep everything that is
        // not ours and re-append the PHP handler if the rewrite would drop it.
        $handler = self::handler($existing);
        $base = rtrim(self::stripLegacy($existing));

        $out = ($base === '' ? '' : $base."\n\n").$block;

        if ($handler !== '' && ! str_contains($out, $handler)) {
            $out .= "\n\n".$handler;
        }

        return rtrim($out)."\n";
    }

    /**
     * Drop the rules generated by versions before the markers, which always
     * started with a known header line. Anything before it (cPanel block, user
     * directives) is preserved.
     */
    private static function stripLegacy(string $existing): string
    {
        $lines = preg_split('/\R/', $existing) ?: [];

        foreach ($lines as $index => $line) {
            foreach (self::LEGACY_HEADERS as $pattern) {
                if (preg_match($pattern, trim($line)) === 1) {
                    return implode("\n", array_slice($lines, 0, $index));
                }
            }
        }

        return $existing;
    }
}
